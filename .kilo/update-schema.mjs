// Builds kilo.schema.json: Kilo's official schema, adjusted to what the Kilo bundled with the VS Code extension (7.8.27) actually accepts.
// Each change below was tested against that version.
//
//   npm run kilo:schema        (re-run after a Kilo update)
//
// Writes two copies, so the editor validates both configs against the same rules:
//   .kilo/kilo.schema.json          used by .kilo/kilo.jsonc           ("$schema": "./kilo.schema.json")
//   ~/.config/kilo/kilo.schema.json used by ~/.config/kilo/kilo.jsonc  ("$schema": "./kilo.schema.json")
// The published schema (https://app.kilo.ai/config.json) describes Kilo's next format (V2): against it, the working V1 keys show as
// deprecated (`permission`, `provider`) and keys the settings screens write (`indexing`, `mcp_tool_display`) show as not allowed.
//
// When Kilo supports the V2 `providers` / `permissions` keys, point both `$schema` lines back at https://app.kilo.ai/config.json and delete
// this script and both copies.
import { existsSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const SOURCE = "https://app.kilo.ai/config.json";
const schema = await (await fetch(SOURCE)).json();
const props = schema.properties;

// 1. `provider` and `permission` are marked deprecated, but 7.8.27 needs them.
for (const key of ["provider", "permission"]) delete props[key].deprecated;

// 2. V2-only keys that 7.8.27 rejects ("V2 permissions are not supported by OpenCode V1"). Remove them so autocomplete never offers them.
for (const key of ["providers", "permissions", "plugins", "websearch", "warming"]) delete props[key];
delete schema.$defs["Config.AgentEncoded"].properties.permissions;

// 3. Model fields only accept the ~9k models.dev catalog IDs, so any local model is flagged.
// Accept any "<provider-id>/<model-id>" instead.
const MODELS_DEV = "https://models.dev/model-schema.json#/$defs/Model";
(function walk(node) {
  if (Array.isArray(node)) return node.forEach(walk);
  if (!node || typeof node !== "object") return;
  if (node.$ref === MODELS_DEV) {
    delete node.$ref;
    Object.assign(node, { type: "string", pattern: "^[^/]+/.+$" });
  }
  Object.values(node).forEach(walk);
})(schema);

// 4. Keys the extension's settings screens write that the published schema lacks (`additionalProperties: false` flags them).
//    Field names and values are taken from the 7.8.27 extension code. Unknown `indexing` fields stay allowed.
props.mcp_tool_display ??= {
  description: "Controls whether MCP tool blocks are expanded or collapsed by default in the VS Code chat UI",
  type: "string",
  enum: ["expanded", "collapsed"],
};
const EMBEDDERS = ["openai-compatible", "openai", "ollama", "gemini", "mistral", "kilo", "bedrock", "openrouter", "voyage", "vercel-ai-gateway"];
props.indexing ??= {
  description: "Semantic codebase indexing. Written by Settings > Indexing in the VS Code extension.",
  type: "object",
  properties: {
    provider: { description: "Embedding provider", type: "string", enum: EMBEDDERS },
    model: { description: "Embedding model ID, as the provider names it", type: "string" },
    dimension: {
      description: "Vector length of the embedding model. Required for openai-compatible: Kilo cannot detect it there.",
      type: "integer",
      minimum: 1,
    },
    vectorStore: { description: "Where embeddings are stored. Default: lancedb (local files, no server)", type: "string", enum: ["lancedb", "qdrant"] },
    fileExtensions: { description: "File extensions to index" },
    ...Object.fromEntries(
      EMBEDDERS.map((id) => [
        id,
        {
          description: `Connection settings for the ${id} provider`,
          type: "object",
          properties: {
            baseUrl: { description: "Endpoint base URL. For LM Studio include /v1, e.g. http://host:1234/v1", type: "string" },
            apiKey: { type: "string" },
          },
        },
      ]),
    ),
  },
};

delete schema.$id; // this is a local copy, not the published schema
schema.$comment = `Generated by .kilo/update-schema.mjs from ${SOURCE} on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`;
const text = JSON.stringify(schema, null, 2) + "\n";

writeFileSync(new URL("./kilo.schema.json", import.meta.url), text);
console.log("Wrote .kilo/kilo.schema.json");

const globalDir = join(homedir(), ".config", "kilo");
if (existsSync(globalDir)) {
  writeFileSync(join(globalDir, "kilo.schema.json"), text);
  console.log(`Wrote ${join(globalDir, "kilo.schema.json")}`);
}
